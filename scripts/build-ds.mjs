// Turns the design system bundle (_ds_bundle.js, a browser IIFE using window.React) into an ES module
// src/ds/index.js, and concatenates the token CSS into src/ds/tokens.css.
import fs from "node:fs";
import path from "node:path";

const DS_DIR = fs.readdirSync("design-source/_ds").find((d) => d.startsWith("csi-group-design-system"));
const root = path.join("design-source/_ds", DS_DIR);
const bundle = fs.readFileSync(path.join(root, "_ds_bundle.js"), "utf8");

const re = /\/\/ (components\/[^\n]+\.jsx)\ntry \{ \(\(\) => \{([\s\S]*?)\n\}\)\(\); \} catch/g;
const names = [];
let body = "";
for (const m of bundle.matchAll(re)) {
  const inner = m[2];
  const exp = inner.match(/Object\.assign\(__ds_scope, \{ ([A-Za-z, ]+) \}\);/);
  if (exp) names.push(...exp[1].split(",").map((s) => s.trim()));
  body += `// ${m[1]}\n(() => {${inner}\n})();\n\n`;
}
if (!names.length) throw new Error("no components found in bundle");

const out = `// GENERATED by scripts/build-ds.mjs from the CSI Group design system bundle. Do not edit.
"use client";
import React from "react";
const __ds_scope = {};

${body}
${names.map((n) => `export const ${n} = __ds_scope.${n};`).join("\n")}
`;
fs.mkdirSync("src/ds", { recursive: true });
fs.writeFileSync("src/ds/index.js", out);

const cssFiles = ["tokens/fonts.css", "tokens/colors.css", "tokens/typography.css", "tokens/spacing.css", "tokens/base.css"];
// The Google Fonts @import is dropped here and loaded with a <link> in src/app/layout.tsx instead
// (a bundled stylesheet cannot keep an @import that is not the first rule).
const css = cssFiles
  .map((f) => `/* ${f} */\n` + fs.readFileSync(path.join(root, f), "utf8"))
  .join("\n")
  .replace(/@import url\([^)]*\);?/g, "");
fs.writeFileSync("src/ds/tokens.css", css);
console.log("components:", names.join(", "));

