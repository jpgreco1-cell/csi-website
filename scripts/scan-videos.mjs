// Lists the MP4 files in public/videos so the site only shows a video where a file exists.
// Runs automatically before `npm run dev` and `npm run build`.
// A poster image with the same name (e.g. csi360.jpg) is used when present.
import fs from "node:fs";
import path from "node:path";

const dir = "public/videos";
fs.mkdirSync(dir, { recursive: true });
const files = fs.readdirSync(dir);
const entries = files
  .filter((f) => f.toLowerCase().endsWith(".mp4"))
  .map((f) => {
    const id = f.replace(/\.mp4$/i, "");
    const poster = files.find((p) => p.toLowerCase() === `${id.toLowerCase()}.jpg`);
    const captions = files.find((p) => p.toLowerCase() === `${id.toLowerCase()}.vtt`);
    return [id, { src: `/videos/${f}`, ...(poster ? { poster: `/videos/${poster}` } : {}), ...(captions ? { captions: `/videos/${captions}` } : {}) }];
  });

// YouTube videos the firm already has (content/embeds.json): { "<slot id>": { "youtube": "<video id>", "title": "..." } }.
// They play through a click-to-load player, so nothing from YouTube loads until a visitor presses play.
const embedsFile = "content/embeds.json";
if (fs.existsSync(embedsFile)) {
  const embeds = JSON.parse(fs.readFileSync(embedsFile, "utf8"));
  for (const [id, e] of Object.entries(embeds)) {
    const poster = files.find((p) => p.toLowerCase() === `${id.toLowerCase()}.jpg`);
    entries.push([id, { youtube: e.youtube, title: e.title, ...(poster ? { poster: `/videos/${poster}` } : {}) }]);
  }
}

const out = `// GENERATED by scripts/scan-videos.mjs from public/videos and content/embeds.json. Do not edit.
export const VIDEOS: Record<string, { src?: string; youtube?: string; title?: string; poster?: string; captions?: string }> = ${JSON.stringify(Object.fromEntries(entries), null, 2)};

/** True for every video id that has a file, for use in the page templates ({{ videos.csi360 }}). */
export const VIDEO_FLAGS: Record<string, boolean> = Object.fromEntries(Object.keys(VIDEOS).map((k) => [k, true]));
`;
fs.writeFileSync(path.join("src/site", "videos.generated.ts"), out);
console.log("videos:", entries.map(([id]) => id).join(", ") || "(none)");
